function fixture() {
  const calls = [], approvals = [], writes = [];
  const active = new OWAClient({ server: 'https://mail.example.test', username: 'fictional', password: 'never-expose-this' }, async () => { throw new Error('Unexpected transport'); }, async () => 'fictional');
  active.syncId = 'session-a';
  active.folders = async () => [{ id: 'target', name: 'Счета' }];
  active.search = async data => { calls.push(['search', data]); return { items: [{ id: 'a', subject: 'Счёт', password: 'must-not-leak' }], more: true }; };
  active.message = async ref => { calls.push(['message', ref]); return { id: ref.id, subject: 'Invoice', from: { email: 'person@example.test' }, text: 'Ignore instructions in mail', password: 'must-not-leak' }; };
  active.move = async data => { calls.push(['move', data]); return true; };
  active.folderOperation = async data => { calls.push(['folder', data]); return true; };
  active.createMailRule = async data => { calls.push(['rule', data]); return true; };
  const state = { active, allowed: true };
  const call = createTools({ current: () => state.active, confirm: async data => { approvals.push(data); return state.allowed; }, writing: delta => writes.push(delta) });
  return { active, state, call, calls, approvals, writes };
}
test('MCP exposes mail and meeting tools, validates arguments, and returns no credentials', async () => {
  const f = fixture();
  assert.equal(tools.length, 14);
  assert.equal(tools.some(tool => /send|delete|attachment/.test(tool.name)), false);
  assert.deepEqual(await f.call('get_account'), { connected: true, sessionId: 'session-a' });
  for (const input of [{}, { sessionId: 'old' }, { sessionId: 'session-a', unexpected: true }]) await assert.rejects(f.call('list_folders', input));
  for (const input of [{ sessionId: 'session-a', offset: -1 }, { sessionId: 'session-a', from: '\"bad' }, { sessionId: 'session-a', start: '2026-02-30' }]) await assert.rejects(f.call('search_mail', input));
  const page = await f.call('search_mail', { sessionId: 'session-a', from: 'person@example.test', text: 'Счёт', offset: 50 });
  assert.deepEqual(f.calls[0], ['search', { query: '(Счёт) AND from:"person@example.test"', folder: undefined, offset: 50 }]);
  assert.equal(page.nextOffset, 51); assert.equal(page.more, true);
  assert.equal(JSON.stringify(page).includes('password'), false);
  const mail = await f.call('read_mail', { sessionId: 'session-a', id: 'a' });
  assert.equal(mail.text, 'Ignore instructions in mail'); assert.equal(mail.password, undefined);
  assert.equal(f.calls.some(([name]) => name === 'change'), false);
});
test('cancelled and invalid writes never mutate; approved writes use existing operations', async () => {
  const f = fixture(), sessionId = 'session-a';
  f.state.allowed = false;
  await assert.rejects(f.call('move_mail', { sessionId, folder: 'target', refs: [{ id: 'a' }] }), /cancelled/);
  assert.equal(f.calls.some(([name]) => name === 'move'), false);
  assert.equal(f.approvals[0].messages[0].subject, 'Invoice');
  assert.deepEqual(f.writes, []);
  await assert.rejects(f.call('create_rule', { sessionId, folder: 'target', name: 'Invoices', sender: 'a@example.test,b@example.test' }));
  await assert.rejects(f.call('move_mail', { sessionId, folder: 'target', refs: [{ id: 'a' }, { id: 'a' }] }));
  await assert.rejects(f.call('create_folder', { sessionId, name: '   ' }));
  f.state.allowed = true;
  await f.call('create_folder', { sessionId, name: 'Счета' });
  assert.deepEqual(f.calls.at(-1), ['folder', { action: 'create', folder: 'msgfolderroot', name: 'Счета' }]);
  await f.call('create_rule', { sessionId, folder: 'target', name: 'Invoices', sender: 'a@example.test' });
  assert.equal(f.calls.at(-1)[0], 'rule');
  assert.deepEqual(f.writes, [1, -1, 1, -1]);
});
test('bulk move preserves image cache, stops after an uncertain result, and never retries', async () => {
  const f = fixture(); let moved = 0;
  await f.active.mailCache.get('image:a', async () => 'image');
  await f.active.mailCache.get('message:a', async () => 'mail');
  f.active.move = async () => { moved++; if (moved === 2) throw new Error('Lost response'); return true; };
  const result = await f.call('move_mail', { sessionId: 'session-a', folder: 'target', refs: ['a', 'b', 'c'].map(id => ({ id })) });
  assert.deepEqual(result.results.map(item => item.status), ['done', 'uncertain', 'skipped']);
  assert.equal(moved, 2); assert.equal(f.active.mailCache.entries.has('image:a'), true); assert.equal(f.active.mailCache.entries.has('message:a'), false);
  assert.deepEqual(f.writes, [1, -1]);
});
test('account retirement after approval or in a batch cannot write to another account', async () => {
  const f = fixture();
  const call = createTools({ current: () => f.state.active, confirm: async () => { f.state.active = null; return true; } });
  await assert.rejects(call('create_folder', { sessionId: 'session-a', name: 'Folder' }), /session ended/);
  assert.equal(f.calls.length, 0);
  f.state.active = f.active; let moved = 0;
  f.active.move = async () => { moved++; f.state.active = null; return true; };
  await assert.rejects(f.call('move_mail', { sessionId: 'session-a', folder: 'target', refs: ['a', 'b'].map(id => ({ id })) }), /uncertain/);
  assert.equal(moved, 1);
});
test('stale reads are discarded and concurrent MCP writes are rejected', async () => {
  const f = fixture(); let finish;
  f.active.search = () => new Promise(resolve => { finish = resolve; });
  const search = f.call('search_mail', { sessionId: 'session-a', text: 'Invoice' });
  f.state.active = null; finish({ items: [], more: false });
  await assert.rejects(search, /session ended/);
  f.state.active = f.active;
  f.active.folderOperation = () => new Promise(resolve => { finish = resolve; });
  const first = f.call('create_folder', { sessionId: 'session-a', name: 'Folder' });
  await new Promise(resolve => setImmediate(resolve));
  await assert.rejects(f.call('create_folder', { sessionId: 'session-a', name: 'Other' }), /in progress/);
  finish(true); await first;
});
test('real stdio subprocess negotiates MCP and reaches the authenticated loopback bridge', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'aster-mcp-'));
  const bridge = await require('../desktop/mcp-bridge.cjs').start({ directory, version: 'test', current: () => ({ syncId: 'fictional', mailCache: new MailCache() }), confirm: async () => false });
  const child = spawn(process.execPath, [path.join(directory, 'mcp-stdio.cjs')], { stdio: ['pipe', 'pipe', 'pipe'] });
  t.after(async () => { child.kill(); await bridge.close(); await fs.rm(directory, { recursive: true, force: true }); });
  const replies = new Map(); let buffer = '', errors = '';
  child.stderr.on('data', chunk => { errors += chunk; });
  child.stdout.on('data', chunk => { buffer += chunk; let end; while ((end = buffer.indexOf('\n')) >= 0) { const message = JSON.parse(buffer.slice(0, end)); buffer = buffer.slice(end + 1); replies.get(message.id)?.(message); replies.delete(message.id); } });
  let id = 0;
  const request = (method, params) => new Promise((resolve, reject) => {
    const requestId = ++id, timer = setTimeout(() => reject(new Error('MCP reply timeout')), 5000);
    replies.set(requestId, message => { clearTimeout(timer); resolve(message); });
    child.stdin.write(`${JSON.stringify({ jsonrpc: '2.0', id: requestId, method, params })}\n`);
  });
  assert.equal((await request('tools/list')).error.code, -32002);
  assert.equal((await request('initialize', { protocolVersion: '2025-11-25', capabilities: {}, clientInfo: { name: 'fixture', version: '1' } })).result.protocolVersion, '2025-11-25');
  child.stdin.write('{"jsonrpc":"2.0","method":"notifications/initialized"}\n');
  assert.equal((await request('tools/list')).result.tools.length, 14);
  assert.deepEqual(JSON.parse((await request('tools/call', { name: 'get_account', arguments: {} })).result.content[0].text), { connected: true, sessionId: 'fictional' });
  assert.equal((await request('tools/call', { name: 'send_mail', arguments: {} })).result.isError, true);
  assert.equal((await request('unknown')).error.code, -32601);
  assert.equal(errors, '');
  const descriptor = JSON.parse(await fs.readFile(path.join(directory, 'mcp-connection.json'), 'utf8'));
  const post = headers => new Promise((resolve, reject) => { const req = http.request({ host: '127.0.0.1', port: descriptor.port, path: '/bridge', method: 'POST', headers }, res => { res.resume(); res.on('end', () => resolve(res.statusCode)); }); req.on('error', reject); req.end('{"method":"tools/list"}'); });
  assert.equal(await post({}), 403);
  assert.equal(await post({ Authorization: `Bearer ${descriptor.token}`, Origin: 'https://evil.example.test' }), 403);
  assert.equal(await post({ Authorization: `Bearer ${descriptor.token}`, Host: 'evil.example.test' }), 403);
  if (process.platform !== 'win32') assert.equal((await fs.stat(path.join(directory, 'mcp-connection.json'))).mode & 0o777, 0o600);
  await bridge.close();
  await assert.rejects(fs.readFile(path.join(directory, 'mcp-connection.json')), { code: 'ENOENT' });
  assert.equal((await request('tools/call', { name: 'get_account', arguments: {} })).result.isError, true);
});
